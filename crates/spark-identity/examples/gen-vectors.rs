//! Regenerate `tests/vectors.txt`.
//!
//! Run only when the derivation path changes on purpose:
//!
//! ```text
//! cargo run -p spark-identity --example gen-vectors > crates/spark-identity/tests/vectors.txt
//! ```
//!
//! A diff in that file during review means every existing account just lost its
//! history. That is the entire reason the vectors are committed.

use spark_crypto::Mnemonic;
use spark_identity::Identity;

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn main() {
    println!("# Frozen derivation vectors for docs/protocol.md §2.");
    println!("# Generated by `cargo run -p spark-identity --example gen-vectors`.");
    println!("# A change here is a change to every user's account. See the example's docs.");

    for (label, entropy) in [
        ("zero", [0u8; 32]),
        ("counting", core::array::from_fn(|i| i as u8)),
    ] {
        let m = Mnemonic::from_entropy(&entropy);
        let id = Identity::from_mnemonic(&m);
        let pubs = id.public();
        println!();
        println!("[{label}]");
        println!("entropy = {}", hex(&entropy));
        println!("phrase = {}", m.phrase().as_str());
        println!("seed = {}", hex(m.to_seed().expose()));
        println!("sign_pub = {}", hex(pubs.sign.as_bytes()));
        println!("kem_pub = {}", hex(pubs.kem.as_bytes()));
        println!("addr = {}", id.addr().to_hex());
        println!("keyring_key = {}", hex(id.keyring_key().expose()));
    }
}
